#!/usr/bin/env julia

"""
Plot the mean oscillator energy ⟨n̂⟩ vs time for every R in the R-sweep data
generated by scripts/compute_mean_energy_R_sweep.jl, together with its stored
power-law fit.

First generate the data once with:

    julia --project=. scripts/compute_mean_energy_R_sweep.jl

which writes data/mean_energy_R_sweep.jld2. Then run this script:

    julia --project=. scripts/plot_mean_energy_R_sweep.jl

Environment variables:
    INPUT_FILE   JLD2 data archive to load
                 default: data/mean_energy_R_sweep.jld2
    OUTPUT_FILE  plot file to write
                 default: plot/mean_energy_R_sweep.pdf
    SCALE        linear, loglog, semilogx, or semilogy
                 default: loglog
    COLORMAP     matplotlib colormap name used to color the traces by R
                 default: viridis
    SHOW_FITS    "1"/"true" to also draw the dashed power-law fits, "0"/"false"
                 to draw only the data.  default: true
    R_SELECT     optional comma-separated list of R values to plot, e.g.
                 "1.99,2.0,2.01"; overrides the SELECTED_R array below.

Which R values are drawn is controlled by the SELECTED_R array in this file
(edit it directly).  When at least one R is selected, only those R values
present in the archive are drawn and the colormap is normalized to that subset.

The archive stores a `datasets` vector, one entry per parameter set
(N, K, omega, n, t_max).  The DATASET environment variable (1-based index,
default 1) selects which entry to plot; a per-entry `runs` vector then holds
one NamedTuple per R: (R, omega, time, energy, m, fit_t, fit_energy).  R
values whose fit failed have m = NaN and empty fit arrays and are therefore
drawn without a fit line.
"""

ENV["MPLBACKEND"] = get(ENV, "MPLBACKEND", "Agg")

using JLD2
using PythonPlot

const plt = PythonPlot
const mpl = PythonPlot.pyimport("matplotlib")
include("publication_plot_style.jl")

data_dir = joinpath(@__DIR__, "..", "data")
plot_dir = joinpath(@__DIR__, "..", "plot")

const default_input_file = joinpath(data_dir, "mean_energy_R_sweep.jld2")
const default_output_file = joinpath(plot_dir, "mean_energy_R_sweep.pdf")

input_file = get(ENV, "INPUT_FILE", default_input_file)
output_file = get(ENV, "OUTPUT_FILE", default_output_file)
scale = Symbol(get(ENV, "SCALE", "loglog"))
colormap = get(ENV, "COLORMAP", "viridis")
show_fits = lowercase(get(ENV, "SHOW_FITS", "true")) in ("1", "true", "yes")

isfile(input_file) ||
    throw(ArgumentError("input file not found: $(normpath(input_file)). Run scripts/compute_mean_energy_R_sweep.jl first."))

data = jldopen(input_file, "r") do file
    (datasets=Vector(file["datasets"]),)
end

datasets = data.datasets
isempty(datasets) && throw(ArgumentError("the archive contains no datasets."))

# The archive may hold several parameter sets (different N/K/omega/n/t_max).
# DATASET (1-based, default 1) picks which one to plot.
dataset_idx = get(ENV, "DATASET", "1")
idx = tryparse(Int, dataset_idx)
isnothing(idx) &&
    throw(ArgumentError("DATASET must be an integer; got '$dataset_idx'."))
1 <= idx <= length(datasets) ||
    throw(ArgumentError("DATASET index $idx out of range 1:$(length(datasets))."))
dataset = datasets[idx]

runs = dataset.runs

println("Plotting dataset $idx/$(length(datasets)): " *
        "(N, K, omega, n, t_max) = ($(dataset.N), $(dataset.K), $(dataset.omega), " *
        "$(dataset.n), $(dataset.t_max)), $(length(runs)) R values")

# Which R values to plot.  Edit this list directly: to plot every R in the
# archive, set it to an empty array `Float64[]`.  An R that is not present in
# the archive is simply skipped.  The environment variable R_SELECT (a
# comma-separated list) overrides this array if set, e.g.
#   R_SELECT="1.99,2.0,2.01" julia --project=. scripts/plot_mean_energy_R_sweep.jl
const SELECTED_R = [1.999, 2.0, 2.001]  # <-- edit here to change which R are drawn

selected = haskey(ENV, "R_SELECT") && !isempty(get(ENV, "R_SELECT", "")) ?
    parse.(Float64, split(get(ENV, "R_SELECT", ""), ',')) : SELECTED_R

if !isempty(selected)
    runs = filter(run -> run.R in selected, runs)
    isempty(runs) &&
        throw(ArgumentError("selected R values did not match any R in the archive: $(selected)"))
end

# A global colormap lets the eye track R across traces.  Use log spacing since
# the R values span many decades around the base.
cmap = mpl.colormaps[colormap]
logR = log.(getproperty.(runs, :R))
logR_min, logR_max = extrema(logR)
logR_span = logR_max - logR_min

fig, ax = plt.subplots(figsize=(6, 4.5))
apply_publication_style!(ax; scale)

for run in runs
    frac = (log(run.R) - logR_min) / logR_span
    color = cmap(frac)
    m_str = isnan(run.m) ? "no fit" : string(round(run.m, digits=4))
    ax.plot(run.time, run.energy; color=color, linestyle="None",
            marker=".", markersize=2.0, alpha=0.6, zorder=1,
            label="\$R = $(run.R)\\ (m = $m_str)\$")
end

if show_fits
    for run in runs
        isempty(run.fit_t) && continue  # failed fit, nothing to draw
        color = cmap((log(run.R) - logR_min) / logR_span)
        ax.plot(run.fit_t, run.fit_energy; color="white", linewidth=4.0, zorder=3)
        ax.plot(run.fit_t, run.fit_energy; color=color, linestyle="--",
                linewidth=1.2, zorder=4)
    end
end

ax.set_xlabel(raw"$t$")
ax.set_ylabel(raw"$\langle \hat{n} \rangle$")

K = dataset.K
n = dataset.n
ω = dataset.omega
parameter_text = "K = $(K)\n\$\\omega = $(round(ω, sigdigits=5))\$"
ax.text(0.03, 0.97, parameter_text; transform=ax.transAxes, ha="left", va="top",
        fontsize=8, bbox=Dict("boxstyle" => "round,pad=0.3", "facecolor" => "white",
                              "edgecolor" => "0.65", "alpha" => 0.9))

n_R = length(runs)
legend_pos = n_R <= 8 ? "center left" : "lower right"
ax.legend(loc=legend_pos, frameon=false, ncol=1, fontsize=7, markerscale=2)

fig.tight_layout()
mkpath(dirname(output_file))
save_publication_figure(fig, output_file)
PythonPlot.plotclose()

println("Loaded R-sweep data from ", normpath(input_file))
println("Saved R-sweep mean-energy plot to ", normpath(output_file))
